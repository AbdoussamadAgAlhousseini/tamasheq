"use client";

import { useEffect, useState } from "react";

import { API_ERRORS, ApiError, type ApiErrorCode } from "@/lib/api";
import {
  ask,
  type AskResult,
  type DocumentSummary,
  fetchDocument,
  searchKnowledge,
  type Theme,
  THEMES,
} from "@/lib/knowledge";
import { usePreferences } from "@/lib/usePreferences";

import { T } from "./T";
import { useCapability } from "./useCapability";

type SearchState =
  | { kind: "loading" }
  | { kind: "error" }
  | { kind: "ok"; documents: DocumentSummary[] };

function DocumentCard({ doc }: { doc: DocumentSummary }) {
  const [body, setBody] = useState<string | null>(null);
  const [failed, setFailed] = useState(false);
  return (
    <article className="rounded-lg border border-line bg-surface p-4" data-document={doc.id}>
      <h3 className="text-lg font-semibold">{doc.title}</h3>
      <p className="text-xs text-muted">
        <T fr={THEMES[doc.theme].fr} en={THEMES[doc.theme].en} />
        {doc.access_level === "community" && (
          <>
            {" · "}
            <T fr="Réservé aux membres" en="Members only" />
          </>
        )}
      </p>
      <p className="mt-2 whitespace-pre-wrap text-sm">{body ?? doc.excerpt}</p>
      {body === null && (
        <button
          type="button"
          onClick={() =>
            fetchDocument(doc.id)
              .then((d) => setBody(d.body))
              .catch(() => setFailed(true))
          }
          className="mt-2 text-sm text-accent underline"
        >
          <T fr="Lire le document" en="Read the document" />
        </button>
      )}
      {failed && (
        <p role="alert" className="text-sm">
          <T fr={API_ERRORS.network.fr} en={API_ERRORS.network.en} />
        </p>
      )}
      <p className="mt-3 text-xs text-muted">
        <T fr="Source : " en="Source: " />
        {doc.source.url ? (
          <a href={doc.source.url} className="underline">
            {doc.source.title}
          </a>
        ) : (
          doc.source.title
        )}
        {doc.author_credit && (
          <>
            {" · "}
            <T fr="Contribution : " en="Contributed by: " />
            {doc.author_credit}
          </>
        )}
        {" · "}
        <T fr="Droits : " en="Rights: " />
        {doc.license}
      </p>
    </article>
  );
}

function Ask() {
  const status = useCapability("knowledge_qa");
  const [question, setQuestion] = useState("");
  const [pending, setPending] = useState(false);
  const [result, setResult] = useState<AskResult | null>(null);
  const [error, setError] = useState<ApiErrorCode | null>(null);

  if (status !== "experimental" && status !== "evaluated") return null;

  async function submit(event: React.FormEvent) {
    event.preventDefault();
    if (question.trim().length < 3 || pending) return;
    setPending(true);
    setError(null);
    setResult(null);
    try {
      setResult(await ask(question.trim()));
    } catch (e) {
      setError(e instanceof ApiError ? e.code : "invalid");
    } finally {
      setPending(false);
    }
  }

  return (
    <section aria-labelledby="ask" className="mt-10 rounded-lg border border-line bg-surface">
      <h2 id="ask" className="border-b border-line p-4 text-lg font-semibold">
        <T fr="Poser une question aux documents" en="Ask the documents" />
      </h2>
      <p role="note" className="border-b border-line p-4 text-sm">
        <T
          fr="Expérimental. La réponse est générée par un modèle d'IA à partir des seuls documents publics et validés de la bibliothèque, avec leurs références. Vérifiez-la dans les passages cités ; elle n'est pas vérifiée par l'équipe."
          en="Experimental. The answer is generated by an AI model from the library's public, validated documents only, with references. Check it against the cited passages; it is not verified by the team."
        />
      </p>
      <form onSubmit={submit} className="flex flex-col gap-3 p-4">
        <label htmlFor="ask-input" className="text-sm font-medium">
          <T fr="Votre question" en="Your question" />
        </label>
        <textarea
          id="ask-input"
          dir="auto"
          rows={3}
          maxLength={1000}
          value={question}
          onChange={(e) => setQuestion(e.target.value)}
          className="rounded-md border border-line bg-background p-2"
        />
        <div>
          <button
            type="submit"
            disabled={pending || question.trim().length < 3}
            className="rounded-md bg-accent px-4 py-2 text-sm font-medium text-on-accent disabled:opacity-50"
          >
            {pending ? <T fr="Recherche…" en="Searching…" /> : <T fr="Demander" en="Ask" />}
          </button>
        </div>
        {error && (
          <p role="alert" className="text-sm font-medium">
            <T fr={API_ERRORS[error].fr} en={API_ERRORS[error].en} />
          </p>
        )}
      </form>
      {result && (
        <div className="border-t border-line p-4" aria-live="polite" data-testid="answer">
          {result.answer === null ? (
            <p>
              <T
                fr="Les documents disponibles ne permettent pas de répondre à cette question. Aucune réponse n'a été générée."
                en="The available documents do not answer this question. No answer was generated."
              />
            </p>
          ) : (
            <>
              {result.insufficient_documentation && (
                <p className="mb-2 text-sm font-medium">
                  <T
                    fr="Documentation insuffisante : réponse partielle ou non fondée sur les documents."
                    en="Insufficient documentation: partial answer, or not grounded in the documents."
                  />
                </p>
              )}
              <p dir="auto" className="whitespace-pre-wrap">
                {result.answer}
              </p>
              <p className="mt-1 text-xs text-muted">
                <T
                  fr={`Générée par ${result.model}, non vérifiée.`}
                  en={`Generated by ${result.model}, not verified.`}
                />
              </p>
            </>
          )}
          {result.references.length > 0 && (
            <div className="mt-4">
              <h3 className="text-sm font-semibold">
                <T fr="Passages cités" en="Cited passages" />
              </h3>
              <ol className="mt-2 flex flex-col gap-3">
                {result.references.map((r) => (
                  <li key={r.ref} className="text-sm">
                    <p className="font-medium">
                      [{r.ref}] {r.title}
                    </p>
                    <blockquote className="mt-1 border-l-2 border-line pl-3 whitespace-pre-wrap">
                      {r.passage}
                    </blockquote>
                    <p className="mt-1 text-xs text-muted">
                      <T fr="Source : " en="Source: " />
                      {r.source.title} · <T fr="Droits : " en="Rights: " />
                      {r.license}
                    </p>
                  </li>
                ))}
              </ol>
            </div>
          )}
        </div>
      )}
    </section>
  );
}

export function KnowledgeSearch() {
  const { lang } = usePreferences();
  const [query, setQuery] = useState("");
  const [theme, setTheme] = useState<Theme | "">("");
  const [state, setState] = useState<SearchState>({ kind: "loading" });

  useEffect(() => {
    const controller = new AbortController();
    const timer = setTimeout(() => {
      setState({ kind: "loading" });
      searchKnowledge(query.trim(), theme, controller.signal)
        .then((documents) => setState({ kind: "ok", documents }))
        .catch((e: unknown) => {
          if (!(e instanceof DOMException && e.name === "AbortError")) setState({ kind: "error" });
        });
    }, 250);
    return () => {
      clearTimeout(timer);
      controller.abort();
    };
  }, [query, theme]);

  return (
    <>
      <section aria-labelledby="library">
        <h2 id="library" className="text-lg font-semibold">
          <T fr="Bibliothèque" en="Library" />
        </h2>
        <div className="mt-3 flex flex-col gap-3 sm:flex-row">
          <label className="flex flex-1 flex-col text-sm font-medium">
            <T fr="Rechercher dans les documents" en="Search the documents" />
            <input
              type="search"
              dir="auto"
              maxLength={300}
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              className="mt-1 rounded-md border border-line bg-background p-2"
            />
          </label>
          <label className="flex flex-col text-sm font-medium">
            <T fr="Thème" en="Theme" />
            <select
              value={theme}
              onChange={(e) => setTheme(e.target.value as Theme | "")}
              className="mt-1 rounded-md border border-line bg-background p-2"
            >
              <option value="">{lang === "en" ? "All themes" : "Tous les thèmes"}</option>
              {(Object.keys(THEMES) as Theme[]).map((t) => (
                <option key={t} value={t}>
                  {THEMES[t][lang]}
                </option>
              ))}
            </select>
          </label>
        </div>
        <div className="mt-6" aria-live="polite">
          {state.kind === "loading" && (
            <p className="text-sm text-muted">
              <T fr="Recherche…" en="Searching…" />
            </p>
          )}
          {state.kind === "error" && (
            <p role="alert" className="text-sm font-medium">
              <T fr={API_ERRORS.network.fr} en={API_ERRORS.network.en} />
            </p>
          )}
          {state.kind === "ok" && state.documents.length === 0 && (
            <p className="text-sm">
              {query.trim() || theme ? (
                <T fr="Aucun document trouvé." en="No document found." />
              ) : (
                <T
                  fr="Aucun document publié pour l'instant : la bibliothèque se remplit à mesure que des contributions sont validées, avec l'accord des personnes et des communautés concernées."
                  en="No published documents yet: the library fills up as contributions are validated, with the consent of the people and communities concerned."
                />
              )}
            </p>
          )}
          {state.kind === "ok" && state.documents.length > 0 && (
            <ul className="flex flex-col gap-4">
              {state.documents.map((d) => (
                <li key={d.id}>
                  <DocumentCard doc={d} />
                </li>
              ))}
            </ul>
          )}
        </div>
      </section>
      <Ask />
    </>
  );
}
