"use client";

import { useState } from "react";

import { API_ERRORS, ApiError, type ApiErrorCode } from "@/lib/api";
import { DIRECTIONS, langTag, translate, type TranslationResult } from "@/lib/translate";
import { usePreferences } from "@/lib/usePreferences";

import { T } from "./T";
import { useCapability } from "./useCapability";

export function Translator() {
  const status = useCapability("translation");
  const { lang } = usePreferences();
  const [direction, setDirection] = useState(0);
  const [text, setText] = useState("");
  const [variant, setVariant] = useState("");
  const [pending, setPending] = useState(false);
  const [result, setResult] = useState<TranslationResult | null>(null);
  const [error, setError] = useState<ApiErrorCode | null>(null);

  if (status === "loading") return null;
  if (status !== "experimental" && status !== "evaluated") {
    const message = status === "error" ? API_ERRORS.network : API_ERRORS.not_configured;
    return (
      <p role="note" className="rounded-md border border-line bg-surface p-4 text-sm">
        <T fr={message.fr} en={message.en} />
      </p>
    );
  }

  const { source, target } = DIRECTIONS[direction];

  async function submit(event: React.FormEvent) {
    event.preventDefault();
    if (!text.trim() || pending) return;
    setPending(true);
    setError(null);
    setResult(null);
    try {
      setResult(await translate(text.trim(), source, target, variant));
    } catch (e) {
      setError(e instanceof ApiError ? e.code : "invalid");
    } finally {
      setPending(false);
    }
  }

  return (
    <section aria-labelledby="translator" className="rounded-lg border border-line bg-surface">
      <h2 id="translator" className="sr-only">
        <T fr="Traducteur" en="Translator" />
      </h2>
      <p role="note" className="border-b border-line p-4 text-sm">
        <strong>
          <T fr="Expérimental. " en="Experimental. " />
        </strong>
        <T
          fr="Traductions générées par un modèle d'IA dont la qualité en tamasheq n'a pas été évaluée. Elles ne sont pas certifiées et peuvent contenir des mots inexistants. Le texte est transmis au fournisseur du modèle (Anthropic) : n'y mettez ni informations personnelles ni savoirs restreints."
          en="Translations generated by an AI model whose Tamasheq quality has not been evaluated. They are not certified and may contain non-existent words. The text is sent to the model provider (Anthropic): do not include personal information or restricted knowledge."
        />
      </p>

      <form onSubmit={submit} className="flex flex-col gap-3 p-4">
        <div className="flex flex-wrap gap-4">
          <label className="flex flex-col text-sm font-medium">
            <T fr="Direction" en="Direction" />
            <select
              value={direction}
              onChange={(e) => setDirection(Number(e.target.value))}
              className="mt-1 rounded-md border border-line bg-background p-2"
            >
              {DIRECTIONS.map((d, i) => (
                <option key={i} value={i}>
                  {lang === "en" ? d.en : d.fr}
                </option>
              ))}
            </select>
          </label>
          <label className="flex flex-col text-sm font-medium">
            <T fr="Variante (facultatif)" en="Variety (optional)" />
            <input
              value={variant}
              maxLength={200}
              onChange={(e) => setVariant(e.target.value)}
              className="mt-1 rounded-md border border-line bg-background p-2"
            />
          </label>
        </div>
        <label htmlFor="translate-input" className="text-sm font-medium">
          <T fr="Texte à traduire" en="Text to translate" />
        </label>
        <textarea
          id="translate-input"
          lang={langTag(source)}
          dir="auto"
          rows={4}
          maxLength={2000}
          value={text}
          onChange={(e) => setText(e.target.value)}
          className="rounded-md border border-line bg-background p-2"
        />
        <div>
          <button
            type="submit"
            disabled={pending || !text.trim()}
            className="rounded-md bg-accent px-4 py-2 text-sm font-medium text-on-accent disabled:opacity-50"
          >
            {pending ? <T fr="Traduction…" en="Translating…" /> : <T fr="Traduire" en="Translate" />}
          </button>
        </div>
        {error && (
          <p role="alert" className="text-sm font-medium">
            <T fr={API_ERRORS[error].fr} en={API_ERRORS[error].en} />
          </p>
        )}
      </form>

      {result && (
        <div className="border-t border-line p-4" aria-live="polite" data-testid="translation">
          <p className="text-xs font-medium text-muted">
            <T fr="Traduction proposée" en="Proposed translation" />
          </p>
          <p lang={langTag(target)} dir="auto" className="mt-1 whitespace-pre-wrap text-lg">
            {result.translation}
          </p>
          <p className="mt-1 text-xs text-muted">
            <T
              fr={`Générée par ${result.model}, non vérifiée.`}
              en={`Generated by ${result.model}, not verified.`}
            />
            {result.truncated && (
              <>
                {" "}
                <T fr="Réponse incomplète." en="Incomplete answer." />
              </>
            )}
          </p>

          {result.alternatives.length > 0 && (
            <Detail title={<T fr="Autres traductions possibles" en="Other possible translations" />}>
              {result.alternatives.map((a, i) => (
                <li key={i} lang={langTag(target)} dir="auto">
                  {a}
                </li>
              ))}
            </Detail>
          )}
          {result.ambiguities.length > 0 && (
            <Detail title={<T fr="Ambiguïtés" en="Ambiguities" />}>
              {result.ambiguities.map((a, i) => (
                <li key={i} lang="fr">
                  {a}
                </li>
              ))}
            </Detail>
          )}
          {result.notes && (
            <div className="mt-4">
              <h3 className="text-sm font-semibold">
                <T fr="Remarques du modèle" en="Model notes" />
              </h3>
              <p lang="fr" className="mt-1 text-sm">
                {result.notes}
              </p>
            </div>
          )}
          <div className="mt-4 text-sm">
            <h3 className="font-semibold">
              <T fr="Dictionnaire validé" en="Validated dictionary" />
            </h3>
            {result.glossary.length > 0 ? (
              <p className="mt-1">
                <T fr="Entrées utilisées : " en="Entries used: " />
                {result.glossary.map((g, i) => (
                  <span key={g.id}>
                    {i > 0 && ", "}
                    <span lang="taq">{g.headword}</span>
                  </span>
                ))}
              </p>
            ) : (
              <p className="mt-1 text-muted">
                <T
                  fr="Aucune entrée validée du dictionnaire n'a été utilisée."
                  en="No validated dictionary entry was used."
                />
              </p>
            )}
          </div>
          <p className="mt-4 text-sm text-muted">
            <T
              fr="Une erreur ? Les locuteurs disposant d'un compte peuvent proposer une correction ; elle sera relue avant d'entrer au corpus."
              en="A mistake? Speakers with an account can propose a correction; it will be reviewed before entering the corpus."
            />
          </p>
        </div>
      )}
    </section>
  );
}

function Detail({ title, children }: { title: React.ReactNode; children: React.ReactNode }) {
  return (
    <div className="mt-4">
      <h3 className="text-sm font-semibold">{title}</h3>
      <ul className="mt-1 list-disc pl-5 text-sm">{children}</ul>
    </div>
  );
}
